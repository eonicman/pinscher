package submit

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/eonicman/pinscher/internal/probe"
	"github.com/eonicman/pinscher/internal/quirk"
)

// GenerateIssue generates a GitHub issue body for a new quirk submission
func GenerateIssue(deviceQuery string, includeProbe bool) (string, string, error) {
	// Probe current system
	probeResult, err := probe.Probe()
	if err != nil {
		return "", "", fmt.Errorf("probe failed: %w", err)
	}

	// Find the device (shared lookup: probe.FindDevice, 2026-10-17 — this used
	// to be its own inline copy of the same matching rules as
	// internal/diagnose; consolidated so there's one implementation).
	device, err := probe.FindDevice(probeResult, deviceQuery)
	if err != nil {
		return "", "", err
	}

	// Find existing quirks for this device
	var existingQuirks []quirk.Quirk
	if device.Vendor != "" && device.DeviceID != "" {
		existingQuirks = quirk.FindByDevice(device.Vendor, device.DeviceID)
	}
	if device.Driver != "" {
		driverQuirks := quirk.FindByModule(device.Driver)
		existingQuirks = append(existingQuirks, driverQuirks...)
	}

	// Generate issue title
	title := fmt.Sprintf("New quirk: %s %s (%s:%s)", device.Bus, device.Description, device.Vendor, device.DeviceID)
	if device.Driver == "" {
		title += " [NO DRIVER]"
	}

	// Driver status string
	driverStr := device.Driver
	if driverStr == "" {
		driverStr = "(none — no driver loaded)"
	}

	// Generate issue body
	var sb strings.Builder

	sb.WriteString("## Hardware Quirk Submission\n\n")
	sb.WriteString("### Device Information\n\n")
	sb.WriteString("| Field | Value |\n")
	sb.WriteString("|-------|-------|\n")
	sb.WriteString(fmt.Sprintf("| Bus | %s |\n", device.Bus))
	sb.WriteString(fmt.Sprintf("| Vendor:Device | %s:%s |\n", device.Vendor, device.DeviceID))
	sb.WriteString(fmt.Sprintf("| Class | %s (%s) |\n", device.Class, device.ClassName))
	sb.WriteString(fmt.Sprintf("| Driver | %s |\n", driverStr))
	sb.WriteString(fmt.Sprintf("| Description | %s |\n", device.Description))
	sb.WriteString(fmt.Sprintf("| Modalias | %s |\n", device.Modalias))
	if device.Revision != "" {
		sb.WriteString(fmt.Sprintf("| Revision | %s |\n", device.Revision))
	}
	sb.WriteString(fmt.Sprintf("| Hostname | %s |\n", probeResult.Hostname))
	sb.WriteString(fmt.Sprintf("| Kernel | %s |\n", probeResult.Kernel))
	sb.WriteString("\n")

	// Existing quirks
	if len(existingQuirks) > 0 {
		sb.WriteString("### Existing Quirks\n\n")
		for _, q := range existingQuirks {
			sb.WriteString(fmt.Sprintf("- **%s** (%s): %s\n", q.ID, q.Severity, q.Description))
		}
		sb.WriteString("\n")
	} else {
		sb.WriteString("### Existing Quirks\n\nNo existing quirks for this device.\n\n")
	}

	// Template for new quirk
	sb.WriteString("### Proposed Quirk\n\n")
	sb.WriteString("```yaml\n")
	sb.WriteString("id: \n")
	sb.WriteString(fmt.Sprintf("device_ids:\n"))
	sb.WriteString(fmt.Sprintf("  - \"%s:%s\"\n", device.Vendor, device.DeviceID))
	sb.WriteString(fmt.Sprintf("device_names:\n"))
	sb.WriteString(fmt.Sprintf("  - \"%s\"\n", device.Description))
	sb.WriteString(fmt.Sprintf("category: \n"))
	driverDefault := device.Driver
	if driverDefault == "" {
		driverDefault = "(unknown)"
	}
	sb.WriteString(fmt.Sprintf("module: %s\n", driverDefault))
	sb.WriteString("params:\n")
	sb.WriteString("  param_name: value\n")
	sb.WriteString("description: |\n")
	sb.WriteString("  What the quirk is and why it's needed\n")
	sb.WriteString("reason: |\n")
	sb.WriteString("  The war story — what happened, how long it took to debug\n")
	sb.WriteString("citation: \n")
	sb.WriteString("kernel_min: \n")
	sb.WriteString("kernel_max: \n")
	sb.WriteString("severity: \n")
	sb.WriteString("verified: false\n")
	sb.WriteString("```\n\n")

	sb.WriteString("### Diagnosis\n\n")
	sb.WriteString("```\n")
	sb.WriteString(fmt.Sprintf("pinscher diagnose %s\n", deviceQuery))
	sb.WriteString("```\n\n")

	if includeProbe {
		sb.WriteString("### Full Probe Data\n\n")
		sb.WriteString("<details>\n<summary>Full hardware probe (click to expand)</summary>\n\n")
		sb.WriteString("```json\n")
		probeJSON, _ := json.MarshalIndent(probeResult, "", "  ")
		sb.WriteString(string(probeJSON))
		sb.WriteString("\n```\n\n")
		sb.WriteString("</details>\n\n")
	}

	sb.WriteString("---\n\n")
	sb.WriteString("*This issue was generated by `pinscher quirk-submit`. Please fill in the proposed quirk fields above.*\n")

	return title, sb.String(), nil
}

// Suppress unused import
var _ = os.Args
